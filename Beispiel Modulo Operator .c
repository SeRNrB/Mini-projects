//Modulo Operator Beischpiel

#include <stdio.h>

int main() {
    printf("%d\n", 10 % 3); // 10 / 3 = 3 (остаток 1) → Вывод: 1
    printf("%d\n", 15 % 4); // 15 / 4 = 3 (остаток 3) → Вывод: 3
    printf("%d\n", 20 % 5); // 20 делится на 5 без остатка → Вывод: 0
    return 0;
}


/*
Применение оператора %:
Проверка четности/нечетности числа:

число % 2 == 0 → четное
число % 2 != 0 → нечетное
Определение последней цифры числа:

число % 10 → последняя цифра
Круговое движение (например, индексы в массиве):

(i + 1) % N позволяет зациклить индексы от 0 до N-1.
*/